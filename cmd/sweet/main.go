const debugHelp = `debug print the AST generated by the parser

usage: debug <sql>`

func runDebug(args []string) error {
	set := createFlag("debug", debugHelp)
	if err := set.Parse(args); err != nil {
		return err
	}
	for _, f := range set.Args() {
		if err := printTree(f); err != nil {
			return err
		}
	}
	return nil
}

func printTree(file string) error {
	r, err := os.Open(file)
	if err != nil {
		return err
	}
	defer r.Close()

	p, err := parser.NewParser(r)
	if err != nil {
		return err
	}
	for {
		stmt, err := p.Parse()
		if err != nil {
			if errors.Is(err, io.EOF) {
				break
			}
			return err
		}
		ast.Debug(os.Stdout, stmt)
	}
	return nil
}
