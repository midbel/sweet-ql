var errConfig = errors.New("invalid configuration file given")

const sweetHelp = `sweet manipulates sql query

sub commands:

* format
* lint
* parse
* scan
* debug

usage: sweet <command> <args>`

func main() {
	flag.Usage = func() {
		fmt.Println(sweetHelp)
		os.Exit(2)
	}
	flag.Parse()

	commands := map[string]func([]string) error{
		"scan":       runScan,
		"parse":      runParse,
		"format":     runFormat,
		"fmt":        runFormat,
		"lint":       runLint,
		"check":      runLint,
		"verify":     runLint,
		"debug":      runDebug,
		"ast":        runDebug,
		"cyclo":      runCyclo,
		"complexity": runCyclo,
	}

	cmd, ok := commands[flag.Arg(0)]
	if !ok {
		fmt.Fprintf(os.Stderr, "unknown command %s", flag.Arg(0))
		fmt.Fprintln(os.Stderr)
		os.Exit(2)
	}
	args := flag.Args()
	if err := cmd(args[1:]); err != nil {
		fmt.Fprintln(os.Stderr, err)
		os.Exit(1)
	}
}

